from django.utils import timezone
from ai_monitoring.models import AIEvent, ServiceAlert
from tables.models import RestaurantTable, TableEvent
from staff.models import CleaningTask


class AIService:
    CONFIDENCE_THRESHOLD = 0.70

    @classmethod
    def process_incoming_event(cls, hotel, restaurant, source_event_id, event_type, confidence_score, model_name='yolo-table-monitor', model_version='v1.0', table=None, camera=None, raw_payload=None):
        """
        Safe idempotent event processing adhering to SRS Section 4.6 and Database Guide Section 6.
        """
        # 1. Idempotency check: if event already ingested, return existing
        existing = AIEvent.objects.filter(source_event_id=source_event_id).first()
        if existing:
            return existing, False

        # 2. Persist AI observation record
        ai_event = AIEvent.objects.create(
            hotel=hotel,
            restaurant=restaurant,
            table=table,
            camera=camera,
            source_event_id=source_event_id,
            event_type=event_type,
            confidence_score=confidence_score,
            model_name=model_name,
            model_version=model_version,
            raw_payload=raw_payload or {},
            validation_status=AIEvent.ValidationStatus.PENDING,
        )

        # 3. Discard or mark low-confidence detections
        if confidence_score < cls.CONFIDENCE_THRESHOLD:
            ai_event.validation_status = AIEvent.ValidationStatus.IGNORED
            ai_event.save()
            return ai_event, True

        # 4. Apply Business Rules to authoritative table states
        if table:
            cls._apply_business_rules(ai_event, table)

        ai_event.validation_status = AIEvent.ValidationStatus.VALIDATED
        ai_event.save()
        return ai_event, True

    @classmethod
    def _apply_business_rules(cls, ai_event, table):
        old_status = table.operational_status

        # Occupancy Detected
        if ai_event.event_type == AIEvent.EventType.OCCUPANCY_DETECTED:
            if table.operational_status in [RestaurantTable.OperationalStatus.AVAILABLE, RestaurantTable.OperationalStatus.AWAITING_CLEANING]:
                table.operational_status = RestaurantTable.OperationalStatus.OCCUPIED
                table.save()
                TableEvent.objects.create(
                    table=table,
                    from_status=old_status,
                    to_status=table.operational_status,
                    triggered_by=TableEvent.Trigger.AI_DETECTION,
                    reason=f"AI occupancy detection (confidence: {ai_event.confidence_score:.2f})"
                )

        # Customer Departure / Occupancy Released (BR-009, BR-010: MUST require cleaning!)
        elif ai_event.event_type == AIEvent.EventType.OCCUPANCY_RELEASED:
            if table.operational_status == RestaurantTable.OperationalStatus.OCCUPIED:
                table.operational_status = RestaurantTable.OperationalStatus.AWAITING_CLEANING
                table.save()
                TableEvent.objects.create(
                    table=table,
                    from_status=old_status,
                    to_status=table.operational_status,
                    triggered_by=TableEvent.Trigger.AI_DETECTION,
                    reason="Customer departure detected; table transitioned to awaiting cleaning."
                )

                # Automatically dispatch a cleaning task
                CleaningTask.objects.get_or_create(
                    table=table,
                    status=CleaningTask.TaskStatus.PENDING,
                    defaults={
                        'hotel': table.restaurant.hotel,
                        'restaurant': table.restaurant,
                        'priority': CleaningTask.Priority.MEDIUM,
                        'notes': f"Auto-generated by AI departure detection #{ai_event.source_event_id}"
                    }
                )

                # Trigger cleaning service alert
                ServiceAlert.objects.create(
                    hotel=table.restaurant.hotel,
                    restaurant=table.restaurant,
                    table=table,
                    ai_event=ai_event,
                    alert_type=ServiceAlert.AlertType.CLEANING_REQUIRED,
                    priority=ServiceAlert.Priority.MEDIUM,
                    message=f"Table {table.table_number} vacated and awaiting cleaning."
                )

        # Waiter Missing Alert (FR-049)
        elif ai_event.event_type == AIEvent.EventType.WAITER_MISSING:
            ServiceAlert.objects.get_or_create(
                table=table,
                alert_type=ServiceAlert.AlertType.MISSING_WAITER,
                status=ServiceAlert.AlertStatus.NEW,
                defaults={
                    'hotel': table.restaurant.hotel,
                    'restaurant': table.restaurant,
                    'ai_event': ai_event,
                    'priority': ServiceAlert.Priority.HIGH,
                    'message': f"Table {table.table_number} is occupied but service threshold was exceeded without waiter presence."
                }
            )

        # Cleanliness Verification (FR-057, FR-058)
        elif ai_event.event_type == AIEvent.EventType.CLEANLINESS_CLEAN:
            # Table can only transition to AVAILABLE if cleaning was completed or verified
            if table.operational_status in [RestaurantTable.OperationalStatus.CLEANING_IN_PROGRESS, RestaurantTable.OperationalStatus.AWAITING_CLEANING]:
                table.operational_status = RestaurantTable.OperationalStatus.AVAILABLE
                table.save()
                TableEvent.objects.create(
                    table=table,
                    from_status=old_status,
                    to_status=table.operational_status,
                    triggered_by=TableEvent.Trigger.AI_DETECTION,
                    reason="AI cleanliness verification passed; table is now ready and available."
                )
                # Resolve pending cleaning tasks for this table
                CleaningTask.objects.filter(
                    table=table,
                    status__in=[CleaningTask.TaskStatus.PENDING, CleaningTask.TaskStatus.IN_PROGRESS, CleaningTask.TaskStatus.COMPLETED]
                ).update(
                    status=CleaningTask.TaskStatus.VERIFIED_CLEAN,
                    verified_at=timezone.now()
                )
